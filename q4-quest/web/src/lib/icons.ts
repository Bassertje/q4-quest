export interface PixelRun {
  x: number;
  y: number;
  w: number;
  tone: '#' | '+' | '-';
}

/** Merge horizontal runs of the same tone into rectangles (fewer SVG nodes). */
export function pixelRuns(grid: string[]): PixelRun[] {
  const runs: PixelRun[] = [];
  grid.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      const c = row[x];
      if (c === '#' || c === '+' || c === '-') {
        let w = 1;
        while (row[x + w] === c) w++;
        runs.push({ x, y, w, tone: c });
        x += w;
      } else x++;
    }
  });
  return runs;
}

/** An SVG path covering every non-empty pixel (for single-colour use, e.g. the nav). */
export function pixelPath(grid: string[]): string {
  return pixelRuns(grid)
    .map((r) => `M${r.x} ${r.y}h${r.w}v1h-${r.w}z`)
    .join('');
}
